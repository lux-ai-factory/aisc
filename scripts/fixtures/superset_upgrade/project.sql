-- throwaway Postgres, never the stack's.
CREATE ROLE dashboard_ro LOGIN PASSWORD :'ro_password';
CREATE SCHEMA engine;
CREATE SCHEMA project;
CREATE SCHEMA target;
CREATE TABLE project.system (pid uuid PRIMARY KEY, number int NOT NULL);
CREATE TABLE target.target (key text PRIMARY KEY, kind text NOT NULL, component_kind text, label text NOT NULL,
  last_card_number int, engine_component uuid);
CREATE TABLE engine.aisc_backend_evaluation (id bigint PRIMARY KEY, pid uuid NOT NULL, status text NOT NULL,
  created_at timestamptz NOT NULL, system_id uuid);
CREATE TABLE engine.aisc_backend_observation (id bigint PRIMARY KEY, tool text NOT NULL, evaluation_id bigint NOT NULL);
CREATE TABLE engine.aisc_backend_metric (id bigint PRIMARY KEY, name text NOT NULL);
CREATE TABLE engine.aisc_backend_measurement (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pid uuid NOT NULL DEFAULT gen_random_uuid(), score double precision NOT NULL, unit text,
  time timestamptz NOT NULL DEFAULT now(), dimensions jsonb, observation_id bigint NOT NULL, metric_id bigint NOT NULL);
CREATE TABLE engine.aisc_backend_plugin (id bigint PRIMARY KEY, name text NOT NULL, package_name text NOT NULL,
  version text NOT NULL, display_name text NOT NULL);
CREATE TABLE engine.aisc_backend_pluginconfig (id bigint PRIMARY KEY, plugin_id bigint NOT NULL);
CREATE TABLE engine.aisc_backend_evaluationplugin (id bigint PRIMARY KEY, evaluation_id bigint NOT NULL,
  plugin_config_id bigint NOT NULL);
CREATE TABLE engine.aisc_backend_aicomponent (id bigint PRIMARY KEY, pid uuid NOT NULL, name text NOT NULL);
CREATE TABLE engine.aisc_backend_evaluationinput (id bigint PRIMARY KEY, name text NOT NULL,
  evaluation_plugin_id bigint NOT NULL, component_id bigint);

